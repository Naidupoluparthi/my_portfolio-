function ContactFormEnter() {
    document.getElementById('contactButton').style.backgroundColor = 'blue';
    document.getElementById('contactButton').style.color = 'white';
    document.getElementById('contactButton').style.transform = 'scale(1.1)';
}

function ContactFormLeave() {
    document.getElementById('contactButton').style.backgroundColor = 'white';
    document.getElementById('contactButton').style.color = 'rgb(32, 33, 54)';
    document.getElementById('contactButton').style.transform = 'scale(1)';
}
